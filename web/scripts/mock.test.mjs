import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mockRequest, DEMO_PASSWORD } from '../src/lib/mock.ts';

test('Mock auth, concurrency, idempotency and account lifecycle follow the API contract', async () => {
  let csrf = '';
  async function call(path, method = 'GET', body, extra = {}) {
    const response = await mockRequest(path, { method, headers: { 'X-CSRF-Token': csrf, ...extra }, ...(body ? { body: JSON.stringify(body) } : {}) });
    const data = response.status === 204 ? null : await response.json();
    if (data?.csrfToken) csrf = data.csrfToken;
    return { response, data };
  }
  assert.equal((await call('/hosts')).response.status, 401);
  await call('/auth/csrf');
  assert.equal((await call('/auth/login', 'POST', { username: 'admin', password: 'wrong' })).data.code, 'INVALID_CREDENTIALS');
  const login = await call('/auth/login', 'POST', { username: 'admin', password: DEMO_PASSWORD });
  assert.equal(login.response.status, 200);
  const self = login.data.user.id;
  assert.equal((await call('/admin/users', 'POST', {}, { 'X-CSRF-Token': 'invalid' })).response.status, 403);
  const hosts = (await call('/hosts')).data.items;
  assert.equal(hosts.length, 6);
  const host = hosts[0];
  const service = (await call(`/hosts/${host.id}/services`)).data.items[0];
  const servicePath = `/hosts/${host.id}/services/${service.id}`;
  const version = (await call(servicePath)).response.headers.get('ETag');
  assert.equal((await call(`${servicePath}/restart`, 'POST', { reason: 'check' }, { 'Idempotency-Key': 'missing-version' })).response.status, 428);
  assert.equal((await call(`${servicePath}/restart`, 'POST', { reason: 'check' }, { 'Idempotency-Key': 'old-version', 'If-Match': '"stale"' })).response.status, 412);
  const headers = { 'Idempotency-Key': crypto.randomUUID(), 'If-Match': version };
  const body = { reason: '验证受控重启', timeoutSeconds: 60 };
  const accepted = await call(`${servicePath}/restart`, 'POST', body, headers);
  assert.equal(accepted.response.status, 202);
  assert.equal(accepted.data.status, 'PENDING');
  const replay = await call(`${servicePath}/restart`, 'POST', body, headers);
  assert.equal(replay.data.id, accepted.data.id);
  assert.equal(replay.response.headers.get('Idempotency-Replayed'), 'true');
  assert.equal((await call(`${servicePath}/restart`, 'POST', { ...body, reason: 'changed' }, headers)).data.code, 'IDEMPOTENCY_KEY_REUSED');
  assert.equal((await call(`${servicePath}/restart`, 'POST', body, { ...headers, 'Idempotency-Key': crypto.randomUUID() })).data.code, 'OPERATION_IN_PROGRESS');
  const settings = await call('/admin/settings');
  const settingsTag = settings.response.headers.get('ETag');
  const { siteName, defaultTimezone, hostOfflineAfterSeconds, operationRetentionDays } = settings.data;
  const settingsBody = { siteName: `${siteName} Test`, defaultTimezone, hostOfflineAfterSeconds, operationRetentionDays };
  assert.equal((await call('/admin/settings', 'PATCH', { ...settingsBody, operationRetentionDays: 1 }, { 'If-Match': settingsTag })).response.status, 422);
  assert.equal((await call('/admin/settings', 'PATCH', settingsBody, { 'If-Match': settingsTag })).response.status, 200);
  assert.equal((await call('/admin/settings', 'PATCH', settingsBody, { 'If-Match': settingsTag })).response.status, 412);
  const selfTag = (await call(`/admin/users/${self}`)).response.headers.get('ETag');
  assert.equal((await call(`/admin/users/${self}`, 'PATCH', { status: 'DISABLED' }, { 'If-Match': selfTag })).data.code, 'ADMIN_CONFLICT');
  const created = await call('/admin/users', 'POST', { username: 'tester', displayName: '测试管理员', initialPassword: 'test-initial-password-2026' });
  assert.equal(created.response.status, 201);
  assert.equal(created.data.mustChangePassword, true);
  await new Promise(resolve => setTimeout(resolve, 3600));
  const result = (await call(`/operations/${accepted.data.id}`)).data;
  assert.equal(result.status, 'SUCCEEDED');
  assert.equal(result.result.activeState, 'ACTIVE');
  assert.ok(result.finishedAt);
  assert.equal(result.error, null);
  await call('/auth/logout', 'POST');
  await call('/auth/csrf');
  const initialLogin = await call('/auth/login', 'POST', { username: 'tester', password: 'test-initial-password-2026' });
  assert.deepEqual(initialLogin.data.permissions, []);
  assert.equal((await call('/hosts')).data.code, 'PASSWORD_CHANGE_REQUIRED');
  assert.equal((await call('/auth/password', 'PUT', { currentPassword: 'test-initial-password-2026', newPassword: 'test-new-password-2026' })).response.status, 204);
  assert.equal((await call('/auth/me')).response.status, 401);
  await call('/auth/csrf');
  assert.equal((await call('/auth/login', 'POST', { username: 'tester', password: 'test-new-password-2026' })).data.user.mustChangePassword, false);
});
